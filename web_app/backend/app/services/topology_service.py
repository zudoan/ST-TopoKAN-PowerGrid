    def get_learned_feature_graph(self) -> Dict[str, Any]:
        """
        Simulates the Sparse Topology Adjacency Matrix generated by the
        Enhanced_SparseTopologyEncoder (Top-K sparse graph).
        """
        n = len(self.node_labels)
        np.random.seed(42)
        
        # Base realistic correlation
        adj = np.zeros((n, n))
        
        # Feeders strongly connected to P_224
        p224_idx = 4
        for f_idx in [0, 1, 2, 3]:
            weight = 0.75 + 0.2 * np.random.rand()
            adj[f_idx, p224_idx] = weight
            adj[p224_idx, f_idx] = weight
            
        # Temperature connected to load (air conditioning & solar generation)
        temp_idx = 5
        solar_idx = 2  # P_478
        adj[temp_idx, p224_idx] = 0.62
        adj[p224_idx, temp_idx] = 0.62
        adj[temp_idx, solar_idx] = 0.78
        adj[solar_idx, temp_idx] = 0.78
        
        # Temporal cycles connected to feeders
        hour_idx = 9
        adj[hour_idx, p224_idx] = 0.85
        adj[hour_idx, 1] = 0.72  # Residential evening peak
        
        # Lag connected to target
        lag_idx = 11
        adj[lag_idx, p224_idx] = 0.91
        adj[p224_idx, lag_idx] = 0.91

        # Self-loops
        for i in range(n):
            adj[i, i] = 1.0

        # Normalization
        matrix_list = []
        for i in range(n):
            row = [round(float(adj[i, j]), 3) for j in range(n)]
            matrix_list.append(row)

        return {
            "nodes": self.node_labels,
            "topk": 4,
            "matrix": matrix_list,
            "sparsity_pct": round((1.0 - (np.count_nonzero(adj) / (n * n))) * 100.0, 1)
        }

